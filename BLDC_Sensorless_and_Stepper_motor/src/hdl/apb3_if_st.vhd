ENTITY apb3_if_st IS
GENERIC (
-- Generic list
    -- Specifies pwdata_i,prdata_o signal width
    g_APB3_IF_DATA_WIDTH               : INTEGER := 32;

    -- Specifies the width of constants
    g_CONST_WIDTH                      : INTEGER := 12;

    -- Specifies the width of adc configuration register
    g_ADC_CONFIG_REG_WIDTH             : INTEGER := 5;

    -- Specifies width of all input and output ports
    g_STD_IO_WIDTH                     : INTEGER := 18
   );
PORT (
-- Port list
    -- APB reset
    preset_i                : IN  STD_LOGIC;

    -- APB clock
    pclk_i                  : IN  STD_LOGIC;

    -- APB slave interface
    psel_i                  : IN  STD_LOGIC;
    pwrite_i                : IN  STD_LOGIC;
    penable_i               : IN  STD_LOGIC;
    paddr_i                 : IN  STD_LOGIC_VECTOR(g_APB3_IF_DATA_WIDTH-1
                                                    DOWNTO 0);
    pwdata_i                : IN  STD_LOGIC_VECTOR(g_APB3_IF_DATA_WIDTH-1
                                                    DOWNTO 0);
    pready_o                : OUT STD_LOGIC;
    pslverr_o               : OUT STD_LOGIC;
    prdata_o                : OUT STD_LOGIC_VECTOR(g_APB3_IF_DATA_WIDTH-1
                                                    DOWNTO 0);

    -- Data Input specifies the ia input of Clarke module
    ia_clarke_in_i          : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the ib input of Clarke module
    ib_clarke_in_i          : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the id output of Park module
    id_park_output_i        : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the iq output of Park module
    iq_park_output_i        : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the valpha output of IPark module
    valpha_ipark_output_i   : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the vbeta output of IPark module
    vbeta_ipark_output_i    : IN STD_LOGIC_VECTOR((G_STD_IO_WIDTH-1) DOWNTO 0);

    -- Data Input specifies the output of ID PI controller
    id_pi_out_i             : IN STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Input specifies the output of IQ PI controller
    iq_pi_out_i             : IN STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Input specifies the step count value
    step_cnt_i              : IN STD_LOGIC_VECTOR(G_STD_IO_WIDTH+5 DOWNTO 0);

    -- Data Input specifies the output angle generated by the stepper theta
    -- gen block
    theta_out_i             : IN STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Input specifies the current sequence controller state
    state_i                 : IN STD_LOGIC_VECTOR(3 DOWNTO 0);

    -- Data Input specifies the raw ADC channel 0 value
    adc_ch0_val_i           : IN STD_LOGIC_VECTOR(11 DOWNTO 0);

    -- Data Input specifies the raw ADC channel 1 value
    adc_ch1_val_i           : IN STD_LOGIC_VECTOR(11 DOWNTO 0);

    -- Data Input specifies the raw ADC channel 2 value
    adc_ch2_val_i           : IN STD_LOGIC_VECTOR(11 DOWNTO 0);

    -- Data Input specifies the raw ADC channel 3 value
    adc_ch3_val_i           : IN STD_LOGIC_VECTOR(11 DOWNTO 0);

    -- Data Output specifies the Kp constant of current PI controller
    idq_pi_kp_o             : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Output specifies the Ki constant of current PI controller
    idq_pi_ki_o             : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Control Output specifies the start motor signal
    start_motor_o           : OUT STD_LOGIC ;

    -- Control Output specifies the stop motor signal
    stop_motor_o            : OUT STD_LOGIC ;

    -- Data Output specifies the sequence controller configuration value
    seq_cntl_config_o       : OUT STD_LOGIC_VECTOR(3 DOWNTO 0);

    -- Data Output specifies the dv value for olmng block
    olmng_dv_o              : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH -1 DOWNTO 0);

    -- Data Output specifies the ADC configuration register value
    adc_control_reg_val_o   : OUT STD_LOGIC_VECTOR(G_ADC_CONFIG_REG_WIDTH-1
                                                    DOWNTO 0);
    -- Data Output specifies the ADC configuration value corresponding to
    -- channel 0
    adc_channel_ch0_o       : OUT STD_LOGIC_VECTOR(15 DOWNTO 0);

    -- Data Output specifies the ADC configuration value corresponding to
    -- channel 1
    adc_channel_ch1_o       : OUT STD_LOGIC_VECTOR(15 DOWNTO 0);

    -- Data Output specifies the ADC configuration value corresponding to
    -- channel 2
    adc_channel_ch2_o       : OUT STD_LOGIC_VECTOR(15 DOWNTO 0);

    -- Data Output specifies the ADC configuration value corresponding to
    -- channel 3
    adc_channel_ch3_o       : OUT STD_LOGIC_VECTOR(15 DOWNTO 0);

    -- Data Output specifies the scaling value for adc_scaling block
    adc_scale_val_o         : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH -1 DOWNTO 0);

    -- Data Output specifies the over-current threshold for the adc_scaling
    -- block
    adc_oc_thresh_o         : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH -1 DOWNTO 0);

    -- Data Output specifies the PWM period value
    pwm_period_val_o        : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH -1 DOWNTO 0);

    -- Data Output specifies the PWM dead time value
    pwm_dead_time_val_o     : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Output specifies the PWM delay time value
    pwm_delay_time_val_o    : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Control Output specifies the stepper theta gen block mode
    theta_gen_mode_o        : OUT STD_LOGIC;

    -- Data Output specifies the stepper theta gen slew count value
    theta_gen_slew_count_o  : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Output specifies the stepper theta gen rate limit value
    theta_gen_rate_limit_o  : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0);

    -- Data Output specifies the stepper theta gen command step number value
    theta_gen_cmd_step_no_o : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH+5 DOWNTO 0);

    -- Data Output specifies the current reference value
    id_ref_val_o            : OUT STD_LOGIC_VECTOR(G_STD_IO_WIDTH-1 DOWNTO 0)
);
END apb3_if_st;
