BEGIN

--=============================================================================
-- Top level output port assignments
--=============================================================================
-- pready_o Is always ready,there will not be any latency from the Fabric
-- modules.
pready_o                              <= '1';
-- Slave error is always '0' as there will not be any slave error.
pslverr_o                             <= '0';

--=============================================================================
-- Generate blocks
--=============================================================================
--NA--

--=============================================================================
-- Asynchronous blocks
--=============================================================================
--------------------------------------------------------------------------
-- Name       : READ_DECODE_PROC
-- Description: Process implements the APB read operation
--------------------------------------------------------------------------
READ_DECODE_PROC:
    PROCESS(paddr_i,ia_clarke_in_i,ib_clarke_in_i,id_park_output_i,
            iq_park_output_i,valpha_ipark_output_i,vbeta_ipark_output_i,
            id_pi_out_i,iq_pi_out_i,adc_ch0_val_i,adc_ch1_val_i,adc_ch2_val_i,
            adc_ch3_val_i,step_cnt_i,theta_out_i, state_i)
BEGIN
    CASE  paddr_i(11 DOWNTO 0)  IS
--------------------
-- C_IA_REG_ADDR
--------------------
        WHEN C_IA_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH-1   DOWNTO 0) <= ia_clarke_in_i;
            prdata_o(g_APB3_IF_DATA_WIDTH-1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>ia_clarke_in_i(17));
--------------------
-- C_IB_REG_ADDR
--------------------
        WHEN C_IB_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH-1   DOWNTO 0) <= ib_clarke_in_i;
            prdata_o(g_APB3_IF_DATA_WIDTH-1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>ib_clarke_in_i(17));
--------------------
-- C_ID_PARK_REG_ADDR
--------------------
        WHEN C_ID_PARK_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0)
                <= id_park_output_i(g_STD_IO_WIDTH -1 DOWNTO 0);
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>id_park_output_i(g_STD_IO_WIDTH -1));
--------------------
-- C_IQ_PARK_REG_ADDR
--------------------
        WHEN C_IQ_PARK_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0)
                <= iq_park_output_i(g_STD_IO_WIDTH -1 DOWNTO 0);
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>iq_park_output_i(g_STD_IO_WIDTH -1));
--------------------
-- C_VALPHA_IPARK_REG_ADDR
--------------------
        WHEN C_VALPHA_IPARK_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0)
                <= valpha_ipark_output_i(g_STD_IO_WIDTH -1 DOWNTO 0);
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>valpha_ipark_output_i(g_STD_IO_WIDTH -1));
--------------------
-- C_VBETA_IPARK_REG_ADDR
--------------------
        WHEN C_VBETA_IPARK_REG_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0)
                <= vbeta_ipark_output_i(g_STD_IO_WIDTH -1 DOWNTO 0);
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>vbeta_ipark_output_i(g_STD_IO_WIDTH -1));
--------------------
-- C_ID_PI_OUT_ADDR
--------------------
        WHEN C_ID_PI_OUT_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0) <= id_pi_out_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>id_pi_out_i(g_STD_IO_WIDTH -1));
--------------------
-- C_IQ_PI_OUT_ADDR
--------------------
        WHEN C_IQ_PI_OUT_ADDR =>
            prdata_o(g_STD_IO_WIDTH -1   DOWNTO 0) <= iq_pi_out_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO g_STD_IO_WIDTH)
                <= (OTHERS=>iq_pi_out_i(g_STD_IO_WIDTH -1));
--------------------
-- C_CH0_DATA_VAL_ADDR
--------------------
        WHEN C_CH0_DATA_VAL_ADDR =>
            prdata_o(11   DOWNTO 0) <= adc_ch0_val_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 12) <= (OTHERS=>'0');
 --------------------
-- C_CH1_DATA_VAL_ADDR
--------------------
        WHEN C_CH1_DATA_VAL_ADDR =>
            prdata_o(11   DOWNTO 0) <= adc_ch1_val_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 12) <= (OTHERS=>'0');
--------------------
-- C_CH2_DATA_VAL_ADDR
--------------------
        WHEN C_CH2_DATA_VAL_ADDR =>
            prdata_o(11   DOWNTO 0) <= adc_ch2_val_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 12) <= (OTHERS=>'0');
--------------------
-- C_CH3_DATA_VAL_ADDR
--------------------
        WHEN C_CH3_DATA_VAL_ADDR =>
            prdata_o(11   DOWNTO 0) <= adc_ch3_val_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 12) <= (OTHERS=>'0');
--------------------
-- C_MC_FSM_STATE_ADDR
--------------------
        WHEN C_MC_FSM_STATE_ADDR =>
            prdata_o(3   DOWNTO 0) <= state_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 4) <= (OTHERS=>'0');
--------------------
-- C_STEP_CNT_ADDR
--------------------
        WHEN C_STEP_CNT_ADDR =>
            prdata_o(23 downto 0) <= step_cnt_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 24)
                <= (OTHERS=> step_cnt_i(23));
--------------------
-- C_THETA_O_ADDR
--------------------
        WHEN  C_THETA_O_ADDR =>
            prdata_o(17 downto 0) <= theta_out_i;
            prdata_o(g_APB3_IF_DATA_WIDTH -1 DOWNTO 18)
                <= (OTHERS => theta_out_i(17));
--------------------
-- OTHERS
--------------------
        WHEN OTHERS =>
           prdata_o <= (OTHERS=>'0');
    END CASE;
END PROCESS;

--=============================================================================
